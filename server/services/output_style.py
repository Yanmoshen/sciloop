"""面向研究者的输出：语言风格与排版规范（单一来源）。

为什么单独抽一个模块
--------------------
这套规范原先只以「结构清晰、直指要点」一句带过，等于没有约束 ——
同一个产品里，不同分支的输出风格不一致，读起来像两个人写的。
把规范收在一处后，任何**新增的"面向前端用户"提示词**直接引用它，避免各写一份、慢慢走样。

适用范围（**这是硬边界，不是建议**）
------------------------------------
- ✅ 输出是**给研究者读的自然语言或 Markdown** 的提示词 —— 例如
  `api/v1/chat.py: REPLY_SYSTEM`。
- ❌ **研究节点执行者**（`services/research/prompts.py: SYSTEM_PROMPT`）—— 它必须
  **只输出一个 JSON 对象**，加 Markdown 排版规范会直接与解析契约冲突。
- ❌ **论文草稿**（`services/writing/drafter.py`）—— 走学术写作规范，
  不是对话文体；把「四段式 + 三级标题」套到论文正文上会破坏论文结构。

代价说明：拼进 system prompt 会占用每次调用的输入 token（本常量约 500 字），
这是刻意的取舍 —— 输出质量（评分里 UX 占 20%）优先于这点固定开销。
"""

from __future__ import annotations

__all__ = ["OUTPUT_SECTION_ORDER", "OUTPUT_STYLE"]

#: 需要展开成完整方案时的推荐段落顺序（写进提示词，让模型有稳定骨架可用）
OUTPUT_SECTION_ORDER = ("直接结论", "详细拆解", "对比与选型", "落地建议")

OUTPUT_STYLE = (
    "输出规范（**面向研究者的每一次回复都要遵守**）：\n"
    "排版：\n"
    "- 大模块用 `###` 三级标题，一个标题只对应一个独立主题；标题只写主题词，不写长句；\n"
    "- 并列或分类说明用无序列表 `-`；步骤流程用有序列表 `1. 2. 3.`；"
    "列表紧跟上文标题或段落，前后不单独空行；\n"
    "- 多维对比、分类汇总用表格；列数控制在 3–4 列，表头写清维度，内容一一对应；\n"
    "- 命令与代码用围栏代码块并标注语言，只解释关键逻辑、不写冗余注释；"
    "单行命令或短表达式内嵌在正文里，用反引号标记；\n"
    "- 不同逻辑模块之间空一行；单段控制在 3–5 行，一段只讲一个核心点。\n"
    "语言：\n"
    "- **先给结论再展开**：开篇直接回答核心问题，再分层讲原理与细节；"
    "顺序按「是什么 → 怎么做 → 为什么」；\n"
    "- 中立客观，不用夸张、营销化或情绪化措辞，不用 emoji，不用多余语气助词；\n"
    "- 用准确的技术术语；方案选型要同时讲优点与代价，并给出明确适用场景，"
    "不写「都可以」「随便用」这类模糊表述；\n"
    "- 技术问题先给可操作的落地步骤、再补原理背景；"
    "对比类问题最后必须给出选型建议，不能罗列完信息就结束。\n"
    "加粗：只加粗**核心术语、关键结论、重点名词**；每段控制在 1–2 处，"
    "绝不整句加粗，避免连续大面积加粗。\n"
    "需要展开成完整方案时，按这四段组织：直接结论 → 详细拆解 → 对比与选型 → 落地建议。"
)
